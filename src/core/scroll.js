// Куди везти сторінку після вибору — і як довго їхати.
//
// Без DOM: сюди приходять уже поміряні числа, звідси йде одна координата.
// Через це правило «крок влазить — ставимо по центру, не влазить — під шапку»
// перевіряється тестом, а не оком на телефоні.

/** Просвіт між краєм екрана і кроком. Менше — крок «липне» до краю. */
const GAP = 14;

/**
 * Бажана позиція прокрутки, щоб відкритий крок було видно.
 *
 * Правило одне: рухатись рівно стільки, скільки треба, і ні пікселем більше.
 * Раніше крок ставився по центру екрана — і сторінка їхала навіть тоді, коли
 * дивитись уже було на що. Виглядало це так, ніби блок росте і вниз, і вгору
 * одночасно: низ розгортався, а верх у цю ж мить кудись повз.
 *
 * Тому:
 *   влазить і вже видно  → не рухаємось узагалі, верх стоїть намертво;
 *   влазить, але нижній край за екраном → підтягуємо рівно до нижнього краю,
 *     але не далі, ніж поки заголовок не впреться у верх;
 *   не влазить (крок із календарем) → ведемо заголовок під верх, решту
 *     людина догортає сама.
 *
 * @param {{top:number, height:number}} box крок у координатах документа
 * @param {{height:number, inset:number, max:number, now:number}} view
 *   height — висота вікна, inset — скільки зверху з'їдає липка шапка (якщо є),
 *   max — найбільша можлива прокрутка, now — де сторінка стоїть зараз
 * @returns {number} scrollY, уже обрізаний по межах документа
 */
export function stepScrollTop(box, view) {
  const roomTop = view.inset + GAP;
  const roomBottom = view.height - GAP;
  const top = box.top - view.now;          // де крок зараз на екрані
  const bottom = top + box.height;

  let move = 0;
  if (box.height > roomBottom - roomTop) {
    move = top - roomTop;                  // не влазить — заголовок під верх
  } else if (top < roomTop) {
    move = top - roomTop;                  // виїхав угору — опускаємо сторінку
  } else if (bottom > roomBottom) {
    // Тягнемо рівно до нижнього краю. Заголовок при цьому не може піти вище
    // верхньої межі — це гарантує сама умова гілки: крок влазить у вільне
    // місце, отже його верх лишається всередині.
    move = bottom - roomBottom;
  }

  return Math.max(0, Math.min(view.now + move, Math.max(0, view.max)));
}

/**
 * Скільки триває подорож. Дальня не має бути нескінченною, а близька — не
 * коротшою за розкладку: коли крок обрано, він їде до центру двічі — від
 * згортання кроку над ним (0.5 с) і від прокрутки. Обидва рухи мають іти
 * ОДНАКОВО довго й однаковою кривою, інакше їхні швидкості складаються
 * посередині — і саме це відчувається як ривок, хоч кожен рух окремо плавний.
 * @param {number} distance скільки пікселів їхати (знак не важливий)
 */
export function scrollDuration(distance) {
  return Math.round(Math.max(600, Math.min(1100, 300 + Math.abs(distance))));
}

/**
 * Розгін і гальмування — половина косинуса.
 *
 * Різкість береться не з тривалості, а з піку швидкості посеред дороги.
 * У кубічної кривої він удвічі вищий за середню швидкість, у косинусної —
 * у π/2 (≈1.57) раза. Та сама відстань за той самий час, але без ривка
 * посередині; саме тому тут не «крива з CSS», а ця.
 */
export function easeInOut(t) {
  const p = t < 0 ? 0 : t > 1 ? 1 : t;
  return (1 - Math.cos(Math.PI * p)) / 2;
}
