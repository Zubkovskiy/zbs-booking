// Супровід: який крок зараз веде людину і що їй там сказати.
//
// Без DOM — тут тільки правило «куди дивитись далі», щоб його можна було
// перевірити тестом, а не клікати очима.
//
// Жоден крок не заповнюється за людину. Підставлена відповідь виглядає як
// зроблений вибір, тому наступні кроки просто пролітали повз — людина навіть
// не помічала, що там щось було. Тепер галочку ставить тільки вона сама.

/**
 * Рядок під заголовком активного кроку. Це не команда — заголовок і так каже,
 * що робити. Тут те, чого з екрана не видно: як читати позначки й що не
 * обов'язкове.
 */
export const STEP_HINT = [
  "Ціна вказана поруч із кожною послугою",
  "«Будь-який вільний» — найшвидший варіант",
  "Підсвічені дні мають вільні місця",
  "Закреслені години вже зайняті",
  "Тільки ім'я і телефон, без реєстрації",
];

/**
 * Стан кожного з п'яти кроків. Активний — перший невиконаний.
 * @param {{service:boolean, unit:boolean, day:boolean, time:boolean, contact:boolean}} filled
 * @returns {("done"|"active"|"todo")[]} рівно п'ять станів, для кроків 1–5
 */
export function stepStates(filled) {
  const done = [filled.service, filled.unit, filled.day, filled.time, filled.contact];
  const active = done.indexOf(false);
  return done.map((ok, i) => (ok ? "done" : i === active ? "active" : "todo"));
}

/** Індекс активного кроку, або -1 коли лишилось тільки натиснути кнопку. */
export function activeStep(states) {
  return states.indexOf("active");
}
