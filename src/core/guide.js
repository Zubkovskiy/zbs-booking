// Супровід: який крок зараз веде людину і що їй там сказати.
//
// Без DOM — тут тільки правило «куди дивитись далі», щоб його можна було
// перевірити тестом, а не клікати очима.
//
// Кроки «Пост» і «День» мають готові відповіді ще до першого дотику:
// пост підставлений перший, день — найближчий вільний. Вести туди означало б
// вигадувати людині роботу, тому вони вважаються виконаними одразу.
// Змінити їх усе одно можна будь-коли.

/** Підказка під заголовком кроку. Показується тільки на активному. */
